"""LaTeX (.tex) export — a clean, single-column, ATS-friendly template that
compiles with pdflatex on Overleaf out of the box (only standard packages).

Many engineering applicants maintain their resume in LaTeX, so we hand them a
source file they can keep editing ("Open in Overleaf") instead of a dead PDF.
"""

from __future__ import annotations

import re

from app.models.schemas import TailoredResume

_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}
_UNICODE = {
    "—": "---", "–": "--", "‘": "`", "’": "'", "“": "``", "”": "''",
    "•": r"\textbullet{}", "…": r"\ldots{}", " ": "~", "→": r"$\rightarrow$",
    "₹": "Rs.", "×": r"$\times$", "≥": r"$\geq$", "≤": r"$\leq$", "·": r"\textperiodcentered{}",
}


def tex(s: str | None) -> str:
    """Escape user text for LaTeX (order matters: specials first, then Unicode)."""
    if not s:
        return ""
    out = "".join(_SPECIAL.get(ch, ch) for ch in s)
    for k, v in _UNICODE.items():
        out = out.replace(k, v)
    # Drop characters pdflatex can't typeset with T1 fonts (emoji, CJK, etc.).
    return "".join(ch for ch in out if ord(ch) < 0x0250 or ch in "–—")


def _url(u: str) -> str:
    u = u.strip()
    href = u if re.match(r"^(https?|mailto):", u) else f"https://{u}"
    label = re.sub(r"^(https?://(www\.)?|mailto:)", "", u).rstrip("/")
    safe_href = href.replace("%", r"\%").replace("#", r"\#")
    return r"\href{" + safe_href + "}{" + tex(label) + "}"


def preamble(lay) -> str:
    m = lay.margins
    size = min((10, 11, 12), key=lambda x: abs(x - lay.font_size))
    paper = "letterpaper" if lay.page_size == "Letter" else "a4paper"
    r, g, b = (int(lay.accent[i:i + 2], 16) for i in (1, 3, 5))
    case = {"smallcaps": r"\scshape", "upper": "", "title": ""}[lay.heading_case]
    upper = r"\MakeUppercase" if lay.heading_case == "upper" else ""
    rule = r"[\color{accent}\titlerule]" if lay.heading_rule else ""
    sans = "\\renewcommand{\\familydefault}{\\sfdefault}\n" if lay.font_family == "sans" else ""
    stretch = lay.line_spacing / 1.2
    return rf"""%% Generated by Tailor — single-column, ATS-friendly resume. Compile with pdfLaTeX.
\documentclass[{paper},{size}pt]{{article}}
\usepackage[utf8]{{inputenc}}
\usepackage[T1]{{fontenc}}
\IfFileExists{{lmodern.sty}}{{\usepackage{{lmodern}}}}{{}}
{sans}\usepackage[top={m.top}in,bottom={m.bottom}in,left={m.left}in,right={m.right}in]{{geometry}}
\usepackage{{enumitem}}
\usepackage{{titlesec}}
\usepackage[hidelinks]{{hyperref}}
\usepackage{{xcolor}}
% No f-ligatures: "fi"/"fl" glyphs are a classic cause of garbled ATS text extraction.
\IfFileExists{{microtype.sty}}{{\usepackage[expansion=false,protrusion=false]{{microtype}}\DisableLigatures[f]{{encoding = *, family = *}}}}{{}}
\input{{glyphtounicode}}
\pdfgentounicode=1   % makes the PDF text machine-readable for ATS parsers
\linespread{{{stretch:.2f}}}

\definecolor{{accent}}{{RGB}}{{{r},{g},{b}}}
\pagestyle{{empty}}
\setlength{{\parindent}}{{0pt}}
\setlist[itemize]{{leftmargin=1.2em, itemsep=1pt, topsep=2pt, parsep=0pt}}
\titleformat{{\section}}{{\large{case}\bfseries\color{{accent}}}}{{}}{{0em}}{{{upper}}}{rule}
\titlespacing*{{\section}}{{0pt}}{{8pt}}{{4pt}}

\newcommand{{\entry}}[4]{{%
  \textbf{{#1}}\hfill #2%
  \ifx&#3&\else\\\textit{{#3}}\fi
  #4}}
"""


def resume_tex(r: TailoredResume, layout=None) -> str:
    from app.models.schemas import LayoutSettings

    lay = layout or LayoutSettings()
    L: list[str] = [preamble(lay), r"\begin{document}", ""]
    c = r.candidate.contact
    env = "center" if lay.header_align == "center" else "flushleft"
    L.append(rf"\begin{{{env}}}")
    if r.candidate.name:
        L.append(rf"{{\LARGE\bfseries {tex(r.candidate.name)}}}\\[2pt]")
    if r.candidate.headline:
        L.append(rf"{tex(r.candidate.headline)}\\[2pt]")
    contact = [_url("mailto:" + c.email) if c.email else "", tex(c.phone), tex(c.location), *[_url(l.url) for l in c.links if l.url]]
    contact = [x for x in contact if x]
    if contact:
        L.append(r"\small " + r" \,|\, ".join(contact))
    L += [rf"\end{{{env}}}", ""]

    if lay.show_summary and (s := (r.summary.tailored or r.summary.original)):
        L += [r"\section{Summary}", tex(s), ""]

    if r.skills.groups:
        L += [r"\section{Skills}", r"\begin{itemize}[leftmargin=0pt, label={}]"]
        L += [rf"\item \textbf{{{tex(g.category)}:}} {tex(', '.join(g.items))}" if g.category else rf"\item {tex(', '.join(g.items))}"
              for g in r.skills.groups if g.items]
        L += [r"\end{itemize}", ""]

    def items(lines: list[str]) -> str:
        lines = [x for x in lines if x and x.strip()]
        if not lines:
            return ""
        return "\n" + r"\begin{itemize}" + "\n" + "\n".join(rf"  \item {tex(x)}" for x in lines) + "\n" + r"\end{itemize}"

    def block(title: str, right: str, sub: str, lines: list[str]) -> str:
        return rf"\entry{{{title}}}{{{tex(right)}}}{{{tex(sub)}}}{{{items(lines)}}}" + "\n\\vspace{4pt}\n"

    if r.experience:
        L.append(r"\section{Experience}")
        for e in r.experience:
            title = tex(e.title) + (rf" \textnormal{{--- {tex(e.company)}}}" if e.company else "")
            L.append(block(title, e.dates, e.location, [b.tailored or b.original for b in e.bullets]))
    if r.projects:
        L.append(r"\section{Projects}")
        for p in r.projects:
            title = tex(p.name) + (rf" \textnormal{{\small({_url(p.link)})}}" if p.link else "")
            L.append(block(title, p.dates, ", ".join(p.tech), [b.tailored or b.original for b in p.bullets]))
    if r.education:
        L.append(r"\section{Education}")
        for ed in r.education:
            title = tex(ed.degree) + (rf" \textnormal{{--- {tex(ed.institution)}}}" if ed.institution else "")
            L.append(block(title, ed.dates, ed.location, ed.details))
    if r.certifications:
        L += [r"\section{Certifications}", items(r.certifications).strip(), ""]
    for sec in r.additional_sections:
        if sec.items:
            L += [rf"\section{{{tex(sec.title or 'Additional')}}}", items(sec.items).strip(), ""]

    L.append(r"\end{document}")
    return "\n".join(L) + "\n"
